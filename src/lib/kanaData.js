export function cleanRomajiSlug(romaji) {
  return String(romaji || '')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '');
}

export function getAllKanaItems() {
  const all = [];

  const addFromRows = (rows, section) => {
    rows.forEach((row) => {
      row.items.forEach((item) => {
        if (item) {
          all.push({
            ...item,
            section,
            rowName: row.name,
          });
        }
      });
    });
  };

  addFromRows(GOJUON_ROWS, 'gojuon');
  addFromRows(DAKUON_ROWS, 'dakuon');
  addFromRows(YOON_ROWS, 'yoon');

  return all;
}

export function createKanaCard(item, scriptType = 'hiragana') {
  const isKatakana = scriptType === 'katakana';
  const mainChar = isKatakana ? item.k : item.h;
  const counterpartChar = isKatakana ? item.h : item.k;
  const slug = cleanRomajiSlug(item.r);
  const cardId = `kana-${slug}-${scriptType}`;
  const counterpartId = `kana-${slug}-${isKatakana ? 'hiragana' : 'katakana'}`;

  const categoryName =
    item.section === 'gojuon'
      ? '五十音'
      : item.section === 'dakuon'
      ? '濁音'
      : '拗音';

  return {
    id: cardId,
    _id: cardId,
    content_type: 'kana',
    jlpt_level: null,
    kana_type: scriptType,
    script_group: item.section || 'gojuon',
    character: mainChar,
    counterpart: counterpartChar,
    relationships: [
      {
        card_id: counterpartId,
        relationship_type: 'counterpart',
      },
    ],
    type: scriptType,
    category: categoryName,
    jlpt: '',
    tags: [scriptType, item.section || 'gojuon', categoryName],
    kanji: mainChar,
    reading: mainChar,
    romaji: item.r,
    meaning: `${item.r} (${isKatakana ? 'Katakana' : 'Hiragana'})`,
    definition: `Japanese phonetic kana for syllable "${item.r}"`,
    interval: 0,
    repetitions: 0,
    ease_factor: 2.5,
    easeFactor: 2.5,
    next_review_date: Date.now(),
    dueDate: Date.now(),
    mastered: false,
  };
}

export function generateKanaCards({ scriptType = 'hiragana', section = 'all' }) {
  const items = getAllKanaItems().filter((item) => {
    if (section === 'all') return true;
    return item.section === section;
  });

  return items.map((item) => createKanaCard(item, scriptType));
}

export function calculateKanaMastery(cards = []) {
  if (!Array.isArray(cards) || cards.length === 0) {
    return { total: 0, mastered: 0, percentage: 0 };
  }

  const mastered = cards.filter(
    (c) => c.mastered || (Number(c.repetitions ?? 0) >= 2 && Number(c.interval ?? 0) >= 3)
  ).length;

  const total = cards.length;
  const percentage = Math.round((mastered / total) * 100);

  return { total, mastered, percentage };
}

